"""Draws the xigo wordmark and icon from Space Grotesk 400 (docs/brand.md).

Writes src/brand.ts and public/favicon.svg. Needs fonttools, brotli and shapely:
    pip install fonttools brotli shapely
    python3 scripts/derive-mark.py && npx prettier --write src/brand.ts
"""

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from shapely.geometry import Polygon

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "node_modules/@fontsource/space-grotesk/files/space-grotesk-latin-400-normal.woff2"

X_HEIGHT = 486
ASCENT = 686
DESCENT = -200
OVERSHOOT = -14
CUT = 52
NODE = X_HEIGHT / 3
GAPS = {"x-i": 62, "i-g": 80, "g-o": 78, "o-node": 70}
ICON = {"size": 64, "radius": 14, "ink": 52, "baseline": 49.882}

X_OUTLINE = [
    (43, 0), (239, 248), (49, 489), (144, 489), (290, 300), (304, 300),
    (449, 489), (545, 489), (354, 248), (550, 0), (454, 0), (304, 195),
    (290, 195), (140, 0),
]
RISING_STROKE = [(43, 0), (140, 0), (545, 489), (449, 489)]
INK = {"x": (43, 550), "i": (83, 162), "g": (59, 559), "o": (59, 559)}


def number(value):
    return f"{value:.1f}".rstrip("0").rstrip(".")


def x_with_falling_stroke_cut():
    rising = Polygon(RISING_STROKE)
    falling = Polygon(X_OUTLINE).difference(rising.buffer(CUT, join_style="mitre"))
    return [rising, *falling.geoms]


def polygon_path(polygons, dx):
    return "".join(
        "M"
        + " ".join(
            f"{number(x + dx)} {number(ASCENT - y)}"
            for x, y in list(p.exterior.coords)[:-1]
        )
        + "Z"
        for p in polygons
    )


def glyph_path(glyphs, cmap, char, dx):
    pen = SVGPathPen(glyphs, number)
    glyphs[cmap[ord(char)]].draw(TransformPen(pen, (1, 0, 0, -1, dx, ASCENT)))
    return pen.getCommands()


def main():
    font = TTFont(FONT)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    x_left = -INK["x"][0]
    right = INK["x"][1] + x_left
    x_path = polygon_path(x_with_falling_stroke_cut(), x_left)
    letters = ""
    for char, gap in (("i", "x-i"), ("g", "i-g"), ("o", "g-o")):
        dx = right + GAPS[gap] - INK[char][0]
        letters += glyph_path(glyphs, cmap, char, dx)
        right = INK[char][1] + dx
    radius = NODE / 2
    node_y = ASCENT - (OVERSHOOT + radius)
    node_x = right + GAPS["o-node"] + radius
    width = node_x + radius
    height = ASCENT - DESCENT

    (ROOT / "src/brand.ts").write_text(
        "// Generated by scripts/derive-mark.py from docs/brand.md; do not edit.\n"
        "/** The wordmark's drawing, in font units: the x, the letters igo, the node. */\n"
        "export const MARK = {\n"
        f"  width: {number(width)},\n"
        f"  height: {number(height)},\n"
        f'  x: "{x_path}",\n'
        f'  letters: "{letters}",\n'
        f"  node: {{ cx: {number(node_x)}, cy: {number(node_y)}, r: {number(radius)} }},\n"
        "};\n"
    )

    x_width = INK["x"][1] - INK["x"][0]
    icon_node_x = x_width + GAPS["o-node"] + radius
    scale = ICON["ink"] / (icon_node_x + radius)
    left = (ICON["size"] - ICON["ink"]) / 2
    top = ICON["baseline"] - ASCENT * scale
    (ROOT / "public/favicon.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {ICON["size"]} {ICON["size"]}">\n'
        f'  <rect width="{ICON["size"]}" height="{ICON["size"]}" rx="{ICON["radius"]}" fill="#0e0e0f"/>\n'
        f'  <g transform="translate({number(left)} {number(top)}) scale({scale:.5f})">\n'
        f'    <path class="mark-x" fill="#edebe6" d="{x_path}"/>\n'
        f'    <circle class="mark-node" fill="#e6c79c" cx="{number(icon_node_x)}" cy="{number(node_y)}" r="{number(radius)}"/>\n'
        "  </g>\n"
        "</svg>\n"
    )


if __name__ == "__main__":
    main()
